-- 가게명 alias — 이름 변경 시 구명(舊名) 검색 보존 (dataops 협의 안건 ②·⑤-3)
-- 초기 적재 1,661행은 dataops 가 tsv(store_name_aliases.tsv)로 INSERT (운영 데이터라 마이그레이션 제외)
CREATE TABLE store_name_alias (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id   BIGINT       NOT NULL REFERENCES store (id),
    alias      VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT now(),
    CONSTRAINT uq_store_name_alias UNIQUE (store_id, alias)
);

CREATE INDEX idx_store_name_alias_store ON store_name_alias (store_id);

-- dataops 지속 갱신 경로: 이름 변경 승인 때마다 구명을 추가한다.
-- 롤이 없는 환경(로컬·CI)에서는 조용히 건너뛴다. identity 컬럼은 시퀀스 GRANT 불요
-- (menu INSERT 93k 건이 테이블 권한만으로 동작한 실증).
DO $$
BEGIN
    IF EXISTS (SELECT FROM pg_roles WHERE rolname = 'dataops_writer') THEN
        GRANT INSERT ON store_name_alias TO dataops_writer;
    END IF;
END $$;
