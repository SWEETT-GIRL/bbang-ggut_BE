INSERT INTO store_search_region (store_id, region_id, weight, mapping_type, is_primary)
SELECT k.store_id, d.id, 0.90, 'AUTO', FALSE
FROM _kakao_dong k
JOIN search_region city ON city.name = k.sido AND city.level = 'CITY'
JOIN search_region gu   ON gu.name = k.gu AND gu.parent_region_id = city.id AND gu.level = 'GU'
JOIN search_region d    ON d.name = k.dong AND d.parent_region_id = gu.id
    AND d.level = 'DONG' AND d.is_active = TRUE
JOIN store s ON s.id = k.store_id AND s.status = 'ACTIVE'
ON CONFLICT ON CONSTRAINT uq_store_search_region DO NOTHING;

