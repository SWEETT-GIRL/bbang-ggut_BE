-- (1) 직접 매핑: region_3rd(법정동) == DONG name
-- (2) 연계표 매핑: region_3rd(행정동) → 법정동 → DONG name (행정동≠법정동 보완)
-- (3) 세종: region_3rd → 세종 GU (직접 + 연계표)
-- 전부 mapping_type='AUTO'. 재실행 안전(ON CONFLICT DO NOTHING).

-- ===== (1) 직접 매핑 (CITY 0.30 / GU 0.50 / DONG 0.90) =====
INSERT INTO store_search_region (store_id, region_id, weight, mapping_type, is_primary)
SELECT m.store_id, m.region_id, m.weight, 'AUTO', FALSE FROM (
    -- CITY
    SELECT s.id AS store_id, city.id AS region_id, 0.30 AS weight
    FROM store s
    JOIN search_region_alias ca ON ca.alias = s.region_1st
    JOIN search_region city ON city.id = ca.region_id AND city.level = 'CITY' AND city.is_active = TRUE
    WHERE s.status = 'ACTIVE' AND s.region_1st IS NOT NULL AND s.region_1st <> ''
    UNION ALL
    -- GU (비세종: region_2nd + parent CITY)
    SELECT s.id, gu.id, 0.50
    FROM store s
    JOIN search_region_alias ca ON ca.alias = s.region_1st
    JOIN search_region city ON city.id = ca.region_id AND city.level = 'CITY'
    JOIN search_region gu ON gu.name = s.region_2nd AND gu.parent_region_id = city.id
        AND gu.level = 'GU' AND gu.is_active = TRUE
    WHERE s.status = 'ACTIVE' AND s.region_2nd IS NOT NULL AND s.region_2nd <> ''
    UNION ALL
    -- 세종 GU (region_3rd 직접: 행정동==법정동 케이스)
    SELECT s.id, gu.id, 0.50
    FROM store s
    JOIN search_region_alias ca ON ca.alias = s.region_1st
    JOIN search_region city ON city.id = ca.region_id AND city.level = 'CITY' AND city.name = '세종'
    JOIN search_region gu ON gu.name = s.region_3rd AND gu.parent_region_id = city.id AND gu.level = 'GU'
    WHERE s.status = 'ACTIVE' AND s.region_3rd IS NOT NULL AND s.region_3rd <> ''
    UNION ALL
    -- DONG (비세종: region_3rd 직접)
    SELECT s.id, d.id, 0.90
    FROM store s
    JOIN search_region_alias ca ON ca.alias = s.region_1st
    JOIN search_region city ON city.id = ca.region_id AND city.level = 'CITY'
    JOIN search_region gu ON gu.name = s.region_2nd AND gu.parent_region_id = city.id AND gu.level = 'GU'
    JOIN search_region d ON d.name = s.region_3rd AND d.parent_region_id = gu.id
        AND d.level = 'DONG' AND d.is_active = TRUE
    WHERE s.status = 'ACTIVE' AND s.region_3rd IS NOT NULL AND s.region_3rd <> ''
) m
ON CONFLICT ON CONSTRAINT uq_store_search_region DO NOTHING;

