-- 디저트 이름에서 괄호 브랜드 꼬리표를 뗀다.
--
-- name 은 지도 칩에 그대로 찍힌다. "한정선 요거트 찹쌀떡 (GS25)" 는 칩 하나가 한 줄을 다 먹고,
-- 브랜드는 이미 brand 컬럼에 있어 이름이 또 말할 이유가 없다.
--
-- 별칭(aliases)에는 "GS25 한정선" 이 남아 있어 수집 스크립트의 검색 범위는 그대로다.

UPDATE dessert_item
SET name = '한정선 요거트 찹쌀떡',
    updated_at = NOW()
WHERE name = '한정선 요거트 찹쌀떡 (GS25)';
