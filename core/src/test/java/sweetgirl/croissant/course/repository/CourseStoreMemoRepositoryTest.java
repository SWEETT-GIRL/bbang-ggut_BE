package sweetgirl.croissant.course.repository;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.List;

import javax.sql.DataSource;

import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestInstance;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.annotation.DirtiesContext;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.transaction.annotation.Transactional;

import jakarta.persistence.EntityManager;
import sweetgirl.croissant.course.entity.Course;
import sweetgirl.croissant.course.entity.CourseStore;
import sweetgirl.croissant.course.entity.CourseStoreMemo;
import sweetgirl.croissant.external.aws.S3Service;
import sweetgirl.croissant.member.entity.Member;
import sweetgirl.croissant.store.entity.Store;

/**
 * 소프트 삭제 JPQL 두 개(정류장 단위 · 코스×사람 단위)가 정확히 그 범위만 닫는지,
 * 게스트 이관이 PK 충돌 없이 옮기는지 실제 DB 로 본다.
 *
 * H2 에는 store 테이블이 없다 — Store.location 의 geography 컬럼 DDL 이 실패하고 Hibernate 가 조용히 넘어간다.
 * 이 테스트는 Store 를 읽지 않으므로 id 만 있는 store 테이블을 직접 만들고 getReference 로 FK 만 채운다.
 */
@SpringBootTest(properties = {
	// NON_KEYWORDS=DAY: course_stores.day 가 H2 예약어라 컬럼명으로 못 쓴다. PostgreSQL 은 허용한다.
	"spring.datasource.url=jdbc:h2:mem:course-store-memo-test;MODE=PostgreSQL;"
		+ "DB_CLOSE_DELAY=-1;DB_CLOSE_ON_EXIT=FALSE;NON_KEYWORDS=DAY"
})
@ActiveProfiles("test")
@DirtiesContext(classMode = DirtiesContext.ClassMode.AFTER_CLASS)
@Transactional
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class CourseStoreMemoRepositoryTest {

	private long nextStoreId = 1;

	/**
	 * store 가 없으니 그것을 참조하는 course_stores, 다시 그것을 참조하는 course_store_memos 도 H2 에 없다.
	 * 세 테이블을 마이그레이션과 같은 모양(FK 제외)으로 직접 만든다.
	 * 트랜잭션 밖(별도 커넥션)에서 만든다 — H2 는 DDL 이 열린 트랜잭션을 커밋해 롤백이 깨진다.
	 */
	@BeforeAll
	void createTablesMissingOnH2(@Autowired DataSource dataSource) {
		JdbcTemplate jdbc = new JdbcTemplate(dataSource);
		jdbc.execute("CREATE TABLE IF NOT EXISTS store (id BIGINT PRIMARY KEY)");
		jdbc.execute("""
				CREATE TABLE IF NOT EXISTS course_stores (
					id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
					course_id   BIGINT    NOT NULL,
					store_id    BIGINT    NOT NULL,
					visit_order INTEGER   NOT NULL,
					day         INTEGER   NOT NULL,
					memo        TEXT,
					visit_time  TIME,
					created_at  TIMESTAMP NOT NULL,
					updated_at  TIMESTAMP,
					deleted_at  TIMESTAMP
				)
				""");
		jdbc.execute("""
				CREATE TABLE IF NOT EXISTS course_store_memos (
					course_store_id BIGINT       NOT NULL,
					member_id       BIGINT       NOT NULL,
					content         VARCHAR(200) NOT NULL,
					created_at      TIMESTAMP    NOT NULL,
					updated_at      TIMESTAMP,
					deleted_at      TIMESTAMP,
					PRIMARY KEY (course_store_id, member_id)
				)
				""");
	}

	@MockitoBean
	private S3Service s3Service;

	@Autowired
	private CourseStoreMemoRepository courseStoreMemoRepository;

	@Autowired
	private EntityManager entityManager;

	private Member owner;
	private Member member;
	private Course course;
	private CourseStore firstStop;
	private CourseStore secondStop;

	@BeforeEach
	void setUp() {
		owner = persistMember("방장");
		member = persistMember("지수");
		course = persistCourse(owner);
		firstStop = persistStop(course, "첫째 빵집", 1);
		secondStop = persistStop(course, "둘째 빵집", 2);
	}

	private Member persistMember(String nickname) {
		Member created = new Member(nickname);
		entityManager.persist(created);
		return created;
	}

	private Course persistCourse(Member courseOwner) {
		Course created = Course.createCustom("코스", courseOwner, false);
		entityManager.persist(created);
		return created;
	}

	private CourseStore persistStop(Course target, String storeName, int visitOrder) {
		long storeId = nextStoreId++;
		entityManager.createNativeQuery("INSERT INTO store (id) VALUES (:id)")
			.setParameter("id", storeId)
			.executeUpdate();
		Store store = entityManager.getReference(Store.class, storeId);
		CourseStore stop = CourseStore.create(target, store, visitOrder);
		entityManager.persist(stop);
		entityManager.flush();
		return stop;
	}

	private CourseStoreMemo persistMemo(CourseStore stop, Member author, String content) {
		CourseStoreMemo memo = CourseStoreMemo.of(stop, author, content);
		entityManager.persist(memo);
		entityManager.flush();
		return memo;
	}

	@Test
	@DisplayName("상세 조회는 지운 메모를 빼고, upsert 조회는 지운 행도 같은 PK 로 찾는다")
	void findAll_excludesDeleted_butUpsertLookupIncludesIt() {
		persistMemo(firstStop, owner, "방장 메모");
		CourseStoreMemo deleted = persistMemo(firstStop, member, "지수 메모");
		deleted.softDelete();
		entityManager.flush();

		List<CourseStoreMemo> active = courseStoreMemoRepository
			.findAllByIdCourseStoreIdInAndDeletedAtIsNull(List.of(firstStop.getId(), secondStop.getId()));

		assertThat(active).extracting(CourseStoreMemo::getContent).containsExactly("방장 메모");
		assertThat(active.get(0).getMember().getNickname()).isEqualTo("방장");
		assertThat(courseStoreMemoRepository.findByIdCourseStoreIdAndIdMemberId(firstStop.getId(), member.getId()))
			.isPresent();
	}

	@Test
	@DisplayName("가게를 빼면 그 정류장의 메모만 전원 닫힌다 — 다른 정류장은 그대로")
	void softDeleteAllByCourseStoreId_closesOnlyThatStop() {
		persistMemo(firstStop, owner, "방장 메모");
		persistMemo(firstStop, member, "지수 메모");
		persistMemo(secondStop, owner, "둘째 방장 메모");

		int closed = courseStoreMemoRepository.softDeleteAllByCourseStoreId(firstStop.getId());
		entityManager.clear();

		assertThat(closed).isEqualTo(2);
		assertThat(courseStoreMemoRepository
			.findAllByIdCourseStoreIdInAndDeletedAtIsNull(List.of(firstStop.getId(), secondStop.getId())))
			.extracting(CourseStoreMemo::getContent)
			.containsExactly("둘째 방장 메모");
	}

	@Test
	@DisplayName("나가면 그 사람이 이 코스에 쓴 메모만 닫힌다 — 남의 메모와 다른 코스의 내 메모는 그대로")
	void softDeleteAllByCourseIdAndMemberId_closesOnlyMineInThatCourse() {
		Course otherCourse = persistCourse(member);
		CourseStore otherStop = persistStop(otherCourse, "다른 코스 빵집", 1);
		persistMemo(firstStop, member, "지수 첫째");
		persistMemo(secondStop, member, "지수 둘째");
		persistMemo(firstStop, owner, "방장 메모");
		persistMemo(otherStop, member, "다른 코스의 지수 메모");

		int closed = courseStoreMemoRepository.softDeleteAllByCourseIdAndMemberId(course.getId(), member.getId());
		entityManager.clear();

		assertThat(closed).isEqualTo(2);
		assertThat(courseStoreMemoRepository
			.findAllByIdCourseStoreIdInAndDeletedAtIsNull(
				List.of(firstStop.getId(), secondStop.getId(), otherStop.getId())))
			.extracting(CourseStoreMemo::getContent)
			.containsExactlyInAnyOrder("방장 메모", "다른 코스의 지수 메모");
	}

	@Test
	@DisplayName("게스트 이관: 같은 정류장에 회원 메모가 있으면 게스트 것을 버리고, 나머지는 회원 id 로 옮긴다")
	void guestMigration_removesDuplicatesThenMoves() {
		Member guest = persistMember("게스트");
		persistMemo(firstStop, guest, "게스트 첫째");
		persistMemo(firstStop, member, "지수 첫째"); // 충돌 → 게스트 것 삭제
		persistMemo(secondStop, guest, "게스트 둘째"); // 이관

		int removed = courseStoreMemoRepository.deleteGuestDuplicates(guest.getId(), member.getId());
		int moved = courseStoreMemoRepository.moveOwner(guest.getId(), member.getId());
		entityManager.clear();

		assertThat(removed).isEqualTo(1);
		assertThat(moved).isEqualTo(1);
		assertThat(courseStoreMemoRepository.findByIdCourseStoreIdAndIdMemberId(secondStop.getId(), member.getId()))
			.get()
			.extracting(CourseStoreMemo::getContent)
			.isEqualTo("게스트 둘째");
		assertThat(courseStoreMemoRepository.findByIdCourseStoreIdAndIdMemberId(firstStop.getId(), guest.getId()))
			.isEmpty();
	}
}
