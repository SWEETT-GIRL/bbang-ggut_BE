/**
 * 집계 JPQL 이 활성 정류장만 세는지 실제 DB 로 본다.
 *
 * H2 에는 store 테이블이 없다 — Store.location 의 geography 컬럼 DDL 이 실패하고 Hibernate 가 조용히 넘어간다.
 * 이 테스트는 Store 를 읽지 않으므로 id 만 있는 store 테이블을 직접 만들고 getReference 로 FK 만 채운다
 * (CourseStoreMemoRepositoryTest 와 같은 방식).
 */
@SpringBootTest(properties = {
	// NON_KEYWORDS=DAY: course_stores.day 가 H2 예약어라 컬럼명으로 못 쓴다. PostgreSQL 은 허용한다.
	"spring.datasource.url=jdbc:h2:mem:course-store-test;MODE=PostgreSQL;"
		+ "DB_CLOSE_DELAY=-1;DB_CLOSE_ON_EXIT=FALSE;NON_KEYWORDS=DAY"
})
@ActiveProfiles("test")
@DirtiesContext(classMode = DirtiesContext.ClassMode.AFTER_CLASS)
@Transactional
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class CourseStoreRepositoryTest {

	private long nextStoreId = 1;

	/** 트랜잭션 밖(별도 커넥션)에서 만든다 — H2 는 DDL 이 열린 트랜잭션을 커밋해 롤백이 깨진다. */
	@BeforeAll
	void createTablesMissingOnH2(@Autowired DataSource dataSource) {
		JdbcTemplate jdbc = new JdbcTemplate(dataSource);
		jdbc.execute("CREATE TABLE IF NOT EXISTS store (id BIGINT PRIMARY KEY)");
		jdbc.execute("""
				CREATE TABLE IF NOT EXISTS course_stores (
					id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
					course_id   BIGINT    NOT NULL,
					store_id    BIGINT    NOT NULL,
					visit_order INTEGER   NOT NULL,
					day         INTEGER   NOT NULL,
					memo        TEXT,
					visit_time  TIME,
					created_at  TIMESTAMP NOT NULL,
					updated_at  TIMESTAMP,
					deleted_at  TIMESTAMP
				)
				""");
	}

	@MockitoBean
	private S3Service s3Service;

	@Autowired
	private CourseStoreRepository courseStoreRepository;

	@Autowired
	private EntityManager entityManager;

	private Course course;

	@BeforeEach
	void setUp() {
		Member owner = new Member("방장");
		entityManager.persist(owner);
		course = Course.createCustom("코스", owner, false);
		entityManager.persist(course);
	}

	private CourseStore persistStop(int visitOrder, int day) {
		long storeId = nextStoreId++;
		entityManager.createNativeQuery("INSERT INTO store (id) VALUES (:id)")
			.setParameter("id", storeId)
			.executeUpdate();
		Store store = entityManager.getReference(Store.class, storeId);
		CourseStore stop = CourseStore.createWithDetails(course, store, visitOrder, day, null, null);
		entityManager.persist(stop);
		entityManager.flush();
		return stop;
	}

	@Test
	@DisplayName("가게가 있는 마지막 일차 — 가게가 없으면 0, 뺀 가게의 일차는 세지 않는다")
	void findMaxDayByCourseId_countsOnlyActiveStops() {
		assertThat(courseStoreRepository.findMaxDayByCourseId(course.getId())).isZero();

		persistStop(1, 1);
		persistStop(2, 3);
		CourseStore removed = persistStop(3, 5);
		removed.softDelete();
		entityManager.flush();

		assertThat(courseStoreRepository.findMaxDayByCourseId(course.getId())).isEqualTo(3);
	}
}
