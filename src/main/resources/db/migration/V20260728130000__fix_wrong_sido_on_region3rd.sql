-- 1) 교정한 이름이 이미 있으면 랭킹을 그쪽으로 옮긴다.
WITH target AS (
    SELECT f.id AS bad_id, MIN(g.id) AS good_id
    FROM famous_menu_by_region f
    JOIN region_fix r ON r.bad = f.region3rd
    JOIN famous_menu_by_region g
      ON g.region3rd = r.good AND g.menu_category = f.menu_category
    GROUP BY f.id
)
UPDATE hot_store_ranking h
SET famous_menu_by_region_id = t.good_id
FROM target t
WHERE h.famous_menu_by_region_id = t.bad_id;

-- 2) 랭킹을 옮기고 나면 잘못된 행은 빈 껍데기다. 지운다.
DELETE FROM famous_menu_by_region f
USING region_fix r
WHERE r.bad = f.region3rd
  AND EXISTS (
      SELECT 1 FROM famous_menu_by_region g
      WHERE g.region3rd = r.good AND g.menu_category = f.menu_category
  );

-- 3) 같은 이름이 없던 행은 이름만 바로잡는다.
UPDATE famous_menu_by_region f
SET region3rd = r.good
FROM region_fix r
WHERE r.bad = f.region3rd;

-- 4) 랭킹이 합쳐진 그룹은 순위가 겹칠 수 있어 다시 매긴다.
WITH reranked AS (
    SELECT h.id,
           ROW_NUMBER() OVER (PARTITION BY h.famous_menu_by_region_id ORDER BY h.rank, h.id) AS new_rank
    FROM hot_store_ranking h
    WHERE h.famous_menu_by_region_id IN (
        SELECT g.id FROM famous_menu_by_region g
        JOIN region_fix r ON r.good = g.region3rd
    )
)
UPDATE hot_store_ranking h
SET rank = x.new_rank
FROM reranked x
WHERE h.id = x.id AND h.rank <> x.new_rank;

-- 5) 동 이름만으로 시도를 특정할 수 없는 유일한 경우: 중구 중앙동(부산·울산).
--    잘못 만들어진 '서울_중구_중앙동'은 랭킹이 없는 빈 행이므로 그냥 지운다.
--    실제 데이터는 부산_중구_중앙동·울산_중구_중앙동에 이미 제대로 들어가 있다.
DELETE FROM famous_menu_by_region f
WHERE f.region3rd = '서울_중구_중앙동'
  AND NOT EXISTS (SELECT 1 FROM hot_store_ranking h WHERE h.famous_menu_by_region_id = f.id);
