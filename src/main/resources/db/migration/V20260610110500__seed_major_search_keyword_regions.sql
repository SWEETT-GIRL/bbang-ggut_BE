INSERT INTO search_region (
    name,
    type,
    level,
    center_lat,
    center_lng,
    radius_meters,
    display_order,
    is_active
)
SELECT
    seed.name,
    seed.type,
    'AREA',
    seed.center_lat,
    seed.center_lng,
    seed.radius_meters,
    seed.display_order,
    TRUE
FROM tmp_seed_search_keyword_region seed
WHERE NOT EXISTS (
    SELECT 1
    FROM search_region existing
    WHERE existing.name = seed.name
      AND existing.type = seed.type
);

WITH alias_candidates AS (
    SELECT DISTINCT ON (REGEXP_REPLACE(LOWER(alias_value.alias), '[[:space:]]+', '', 'g'))
        region.id AS region_id,
        alias_value.alias,
        REGEXP_REPLACE(LOWER(alias_value.alias), '[[:space:]]+', '', 'g') AS normalized_alias,
        alias_value.alias = seed.name AS is_primary,
        seed.display_order
    FROM tmp_seed_search_keyword_region seed
    JOIN search_region region
        ON region.name = seed.name
       AND region.type = seed.type
    CROSS JOIN LATERAL UNNEST(seed.aliases) AS alias_value(alias)
    ORDER BY
        REGEXP_REPLACE(LOWER(alias_value.alias), '[[:space:]]+', '', 'g'),
        CASE WHEN alias_value.alias = seed.name THEN 0 ELSE 1 END,
        seed.display_order
)
INSERT INTO search_region_alias (
    region_id,
    alias,
    normalized_alias,
    is_primary
)
SELECT
    alias_candidates.region_id,
    alias_candidates.alias,
    alias_candidates.normalized_alias,
    alias_candidates.is_primary
FROM alias_candidates
WHERE NOT EXISTS (
    SELECT 1
    FROM search_region_alias existing
    WHERE existing.normalized_alias = alias_candidates.normalized_alias
);
