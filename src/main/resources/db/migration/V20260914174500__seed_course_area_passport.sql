-- region_2nd·region_3rd 를 NULL 로 두어 반경만 본다(후보 SQL 의 "둘 다 NULL → 반경만" 모드). 서울 6칸만 구·동을 채운다 —
-- 동은 반경과 거의 같은 범위라 안전하다. 관광지 도장 칸 아래 추천 동네를 여러 개 두는 일(중문·성산·애월 …)은 별도 이슈.
--
-- center: 그 칸 ACTIVE 가게 가운데 "반경 1,200m 안에 같은 칸 가게가 가장 많은 가게"의 좌표(2026-09-14, 랩 = 운영 덤프 08-20,
--   산출 SQL 은 scripts/lab/course-area-seed-centers.sql). 가게 평균은 군집이 여럿인 시군구에서 빈 땅에 떨어지고(창원·서귀포는
--   평균 1,200m 안 가게 0곳), 행정 경계 중심은 면적 중심이라 산·바다로 간다. 최밀집 원은 실제 빵 거리를 잡는다(수원 행궁동·
--   경주 황오동·전주 풍남동·부산 광안동·대구 삼덕동). 같은 칸 가게만 세는 이유: 전체를 세면 중심이 칸 경계로 끌려가 옆 칸과
--   겹친다(대구 수성구가 중구 삼덕동 옆으로 가서 98곳 겹침 → 같은 칸만 세면 범어동, 겹침 0).
-- search_region_id: 중심 1,200m 안에 검색 핫플(HOT_PLACE)이 있으면 가장 가까운 것을 참조만 한다 — 좌표 출처가 아니다.
--   이름으로 찾는다(id 는 환경마다 다를 수 있다). 관광 랜드마크형 핫플(영종도·여수·안목 …)은 빵 동네와 어긋나 안 붙고,
--   용인·파주·충주·조치원읍 등은 핫플 자체가 없다 — 그래서 14칸이 NULL 이다.
-- radius_m: 1,200 고정. 반경 안 가게 수는 최소 26(세종 도담동)·최대 457(연남동)이라 어느 칸이든 4곳 코스가 나온다.
-- max_hop_m: 1,500 으로 통일 — 코스 안 이웃 가게 사이 거리 상한(설계 §5.5), 걸어서 20분. 지역 퍼짐(p80)으로 정하던 초안은
--   버렸다 — 퍼짐은 지역의 넓이이지 한 번에 걸을 거리가 아니다. 서비스가 인기 1위에서 시작해 이 상한 안에서 가까운 가게를
--   이어 붙인다. 랩 시뮬레이션: 상한 1,200 이면 47칸, 1,500 이상이면 48칸 모두 4곳이 나온다. 실제 코스 총거리·구간 분포를 보고
--   #661 에서 조정한다.
-- region_2nd/3rd: 서울 6칸만 store 표기 그대로(성동구 성수동 …). 세종은 시군구가 없어 읍·동인데 도장판대로 조치원읍·도담동
