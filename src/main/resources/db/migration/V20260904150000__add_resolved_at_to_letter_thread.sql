-- 왜 필요한가 — 앱 편지함은 화면에 들어올 때마다 "어떤 이야기인지 골라주세요"를 띄웠다.
-- 유형을 고른 적 있는지가 화면 지역 상태라 진입할 때마다 비어 있었기 때문이다. 그래서
-- 상담을 하다 잠깐 나갔다 오면 처음부터 다시 시작하는 것처럼 보였다.
--
-- 시각을 담는 이유 — boolean 이면 "언제 닫혔는지"가 남지 않는다. 닫힌 뒤 얼마 만에 다시
