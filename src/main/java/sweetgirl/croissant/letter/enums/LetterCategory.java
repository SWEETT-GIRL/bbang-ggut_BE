package sweetgirl.croissant.letter.enums;

/**
 * 사용자가 말을 걸며 고르는 문의 유형.
 *
 * <p>대화방은 사람당 하나라 한 방에 여러 주제가 섞인다. 유형이 메시지에 붙어 있어야
 * 어드민이 "이번 건이 뭐였는지"를 안다.
 *
 * <p>빵집 정보 오류는 일부러 없다 — 제보 기능이 이미 그 길을 맡고 있어서, 여기에 또 두면
 * 같은 제보가 두 군데로 들어온다.
 */
public enum LetterCategory {
	/** 오류가 있어요 */
	BUG,
	/** 이런 기능이 있으면 좋겠어요 */
	SUGGESTION,
	/** 계정·로그인 문제 */
	ACCOUNT,
	/** 그 외 */
	ETC,
	/** 빵별일지 팀이 먼저 건 말 — 인터뷰 요청 같은 것. 사용자는 고를 수 없다. */
	OUTREACH
}
