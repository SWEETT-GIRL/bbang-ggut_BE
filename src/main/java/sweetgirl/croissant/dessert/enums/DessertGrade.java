package sweetgirl.croissant.dessert.enums;

/**
 * 이 가게가 이 디저트를 판다는 근거가 얼마나 센지. 파이프라인이 매일 근거에서 다시 계산한다.
 *
 * <p>서버는 등급으로 거르지 않고 그대로 내려준다. 유행 디저트는 몇 주 팔다 접는 곳이 많아
 * "확실한 곳만" 보여주면 정작 동네에 아무것도 안 남는다. 화면은 이 말을 옮기는 대신
 * 사실(마지막 언급이 언제, 근거가 몇 건)만 적고 판단은 보는 사람에게 남긴다.
 */
public enum DessertGrade {

	/** 최근 후기가 여럿 */
	STRONG,

	LIKELY,

	/** 근거가 약하다 */
	WEAK,

	/** 오래됐다 */
	STALE
}
